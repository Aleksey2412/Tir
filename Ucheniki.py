import pandas as pd

# Данные учеников и их оценки
data = {
    'Имя': ['Иванов Иван', 'Петров Петр', 'Сидоров Алексей', 'Кузнецова Анна', 'Орлов Олег',
            'Васильев Василий', 'Сергеева Мария', 'Попов Павел', 'Федоров Федор', 'Александров Александр'],
    'Русский язык': [4, 5, 3, 4, 5, 3, 4, 5, 4, 3],
    'Математика': [5, 4, 5, 3, 4, 5, 4, 3, 5, 4],
    'Литература': [3, 4, 5, 4, 3, 5, 3, 4, 5, 3],
    'История': [4, 5, 3, 4, 5, 3, 4, 5, 3, 4],
    'География': [5, 4, 3, 5, 4, 3, 5, 4, 3, 5]
}

# Создание DataFrame
df = pd.DataFrame(data)

# Вычисление Q1 и Q3 для оценок по математике
Q1_math = df['Математика'].quantile(0.25)
Q3_math = df['Математика'].quantile(0.75)

# Вычисление средней оценки по каждому предмету
subject_means = df.mean(numeric_only=True)

# Вычисление медианы по каждому предмету
subject_medians = df.median(numeric_only=True)

# Вывод результатов
print(f"Первый квартиль (Q1) для математики: {Q1_math}")
print(f"Третий квартиль (Q3) для математики: {Q3_math}")
print("\nСредние оценки по каждому предмету:")
print(subject_means)
print("\nМедианная оценка по каждому предмету:")
print(subject_medians)
